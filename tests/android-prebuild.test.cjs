const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const manifest=fs.readFileSync(path.join(root,'android/app/src/main/AndroidManifest.xml'),'utf8');
const gradle=fs.readFileSync(path.join(root,'android/app/build.gradle.kts'),'utf8');
const top=fs.readFileSync(path.join(root,'android/build.gradle.kts'),'utf8');
const settings=fs.readFileSync(path.join(root,'android/settings.gradle.kts'),'utf8');
const java=fs.readFileSync(path.join(root,'android/app/src/main/java/com/kalori/journal/MainActivity.java'),'utf8');
assert.match(manifest,/<manifest\b/);
assert.match(manifest,/android:name="\.MainActivity"/);
assert.match(manifest,/android:exported="true"/);
assert.match(manifest,/android:allowBackup="false"/);
assert.match(manifest,/android:usesCleartextTraffic="false"/);
assert.match(gradle,/compileSdk\s*=\s*35/);
assert.match(gradle,/minSdk\s*=\s*26/);
assert.match(gradle,/targetSdk\s*=\s*35/);
assert.match(gradle,/JavaVersion\.VERSION_17/);
assert.match(gradle,/assets\.srcDir\(syncKaloriWebAssets\)/);
for(const filename of ['index.html','history.html','journal-data.js','packaged-foods.js','food-quality.js'])
  assert.ok(gradle.includes('"'+filename+'"'),filename+' missing from generated assets');
assert.match(top,/com\.android\.application/);
assert.match(settings,/include\(":app"\)/);
assert.match(java,/view\.saveState\(webState\)/);
assert.match(java,/view\.restoreState\(previous\)/);
assert.match(java,/if\(stream==null\)throw new IOException/);
assert.match(java,/try\(OutputStream stream=/);
assert.match(java,/uploadCallback\.onReceiveValue\(uri==null\?null:new Uri\[\]\{uri\}\)/);
assert.match(java,/if\(uploadCallback!=null\)\{uploadCallback\.onReceiveValue\(null\)/);
assert.ok(java.indexOf('stream.write(json.getBytes')<java.indexOf('JSON yedeği kaydedildi.'),'success notification must follow write');
assert.match(java,/boolean saved=false/);
assert.ok(java.indexOf('saved=true;')>java.indexOf('catch(Exception error){android.util.Log.e("Kalori","Backup export failed"'),'success flag must follow stream close and error handling');
assert.match(java,/if\(saved\)Toast\.makeText\(this,"JSON yedeği kaydedildi\./);
assert.ok(java.indexOf('if(saved)Toast.makeText')>java.indexOf('catch(Exception error){android.util.Log.e("Kalori","Backup export failed"'),'success must be shown after try-with-resources completes');
console.log('PASS: manifest, Gradle asset wiring, file selection and backup write ordering contracts.');
