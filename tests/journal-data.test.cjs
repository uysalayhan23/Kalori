const assert=require('node:assert/strict');
const journal=require('../journal-data.js');
function storage(initial=null,failWrite=false){let value=initial;return {getItem(){return value},setItem(k,v){if(failWrite)throw Error('quota');value=v},snapshot(){return value}}}
const day='2026-10-12',entry={id:'e1',day,food:'Peynirli sandviç',kcal:250,protein:null,carbs:20,fat:10};
const disk=storage();
let data=journal.read(disk);
assert.deepEqual(data,{entries:[],water:{}});
data=journal.add(data,entry);
journal.write(disk,data);
assert.equal(journal.read(disk).entries[0].food,'Peynirli sandviç');
data=journal.water(data,day,1);
journal.write(disk,data);
assert.equal(journal.read(disk).water[day],1);
data=journal.water(data,day,-1);
assert.equal(data.water[day],0);
data=journal.remove(data,'e1');
journal.write(disk,data);
assert.equal(journal.read(disk).entries.length,0);
const corrupted=storage('{"entries":');
assert.throws(()=>journal.read(corrupted),SyntaxError);
assert.equal(corrupted.snapshot(),'{"entries":');
const missingWater=storage('{"entries":[]}');
assert.throws(()=>journal.read(missingWater),/invalid/);
const refusal=storage(JSON.stringify({entries:[],water:{}}),true);
const previous=refusal.snapshot();
assert.throws(()=>journal.write(refusal,journal.add({entries:[],water:{}},entry)),/quota/);
assert.equal(refusal.snapshot(),previous);
const badBackup={entries:[{...entry,kcal:-5}],water:{}};
assert.equal(journal.valid(badBackup),false);
assert.equal(journal.valid({entries:[entry,entry],water:{}}),false);
assert.equal(journal.valid({entries:[entry],water:{[day]:1}}),true);
const restored=storage(JSON.stringify({entries:[],water:{}}));
journal.write(restored,{entries:[entry],water:{[day]:2}});
assert.equal(journal.read(restored).entries.length,1);
assert.equal(journal.read(restored).water[day],2);
console.log('PASS: add, delete, water, invalid storage, failed writes and JSON restore.');
