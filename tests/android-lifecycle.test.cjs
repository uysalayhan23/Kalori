const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const java=fs.readFileSync(path.join(root,'android/app/src/main/java/com/kalori/journal/MainActivity.java'),'utf8');
const manifest=fs.readFileSync(path.join(root,'android/app/src/main/AndroidManifest.xml'),'utf8');
const journal=require('../journal-data.js');
assert.match(java,/void onSaveInstanceState\(Bundle outState\)/);
assert.match(java,/view\.saveState\(webState\)/);
assert.match(java,/view\.restoreState\(previous\)/);
assert.match(java,/restoreState\(previous\)==null\)\{view\.loadUrl\(ASSET_ORIGIN\+"index\.html"\)/);
assert.match(java,/view\.onPause\(\)/);
assert.match(java,/view\.onResume\(\)/);
assert.match(java,/view\.stopLoading\(\)/);
assert.match(java,/view\.removeJavascriptInterface\("KaloriAndroid"\)/);
assert.match(java,/uploadCallback\.onReceiveValue\(null\)/);
assert.match(java,/pendingBackup=null/);
assert.doesNotMatch(java,/outState\.putString\([^\n]*pendingBackup/);
assert.match(manifest,/android:allowBackup="false"/);
assert.match(manifest,/android:usesCleartextTraffic="false"/);
const row={id:'persist-1',day:'2026-10-12',food:'Öğün',kcal:null};
let raw=null;
const storage={getItem(){return raw},setItem(k,v){raw=v}};
journal.write(storage,journal.add(journal.read(storage),row));
const afterRestart=journal.read(storage);
assert.equal(afterRestart.entries.length,1);
assert.equal(afterRestart.entries[0].food,'Öğün');
assert.equal(afterRestart.entries[0].kcal,null);
