const assert=require('node:assert/strict');
const journal=require('../journal-data.js');
const backing=new Map();
const storage={getItem:key=>backing.get(key)??null,setItem:(key,value)=>backing.set(key,value)};
const lockLog=[];
let tail=Promise.resolve();
const locks={request(name,options,callback){
  assert.equal(name,'kalori_journal_v1_write');
  assert.equal(options.mode,'exclusive');
  const task=tail.then(()=>{lockLog.push('acquire');return callback()});
  tail=task.then(()=>{lockLog.push('release')},()=>{lockLog.push('release')});
  return task;
}};
const day='2026-10-12';
const row=id=>({id,day,food:'Öğün'});
(async()=>{
  const first=journal.lockedUpdate(storage,locks,data=>journal.add(data,row('a')));
  const second=journal.lockedUpdate(storage,locks,data=>journal.add(data,row('b')));
  await Promise.all([first,second]);
  assert.deepEqual(journal.read(storage).entries.map(x=>x.id),['a','b']);
  assert.deepEqual(lockLog,['acquire','release','acquire','release']);
  const legacyRaw=storage.getItem(journal.KEY);
  await assert.rejects(journal.lockedUpdate(storage,null,data=>data),/lock unavailable/);
  assert.equal(storage.getItem(journal.KEY),legacyRaw);
  await assert.rejects(journal.lockedUpdate(storage,locks,async data=>data),/Async transform/);
  assert.equal(storage.getItem(journal.KEY),legacyRaw);
  await assert.rejects(journal.lockedRestore(storage,locks,{entries:[],water:{}},'stale'),/changed before restore/);
  assert.equal(storage.getItem(journal.KEY),legacyRaw);
  await journal.lockedRestore(storage,locks,{entries:[row('restored')],water:{}},legacyRaw);
  assert.deepEqual(journal.read(storage).entries.map(x=>x.id),['restored']);
  const restoredRaw=storage.getItem(journal.KEY);
  await assert.rejects(journal.lockedRestore(storage,null,{entries:[],water:{}},restoredRaw),/lock unavailable/);
  assert.equal(storage.getItem(journal.KEY),restoredRaw);
  const corrupt='{"entries":';
  backing.set(journal.KEY,corrupt);
  await assert.rejects(journal.lockedRestore(storage,locks,{entries:[],water:{}},corrupt));
  assert.equal(storage.getItem(journal.KEY),corrupt);
  console.log('PASS: exclusive queue, two retained entries, stale restore, unavailable locks and corrupt journal fail-closed.');
})().catch(e=>{console.error(e);process.exitCode=1});
